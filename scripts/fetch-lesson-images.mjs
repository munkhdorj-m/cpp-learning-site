// Downloads the pictures chosen in the manifest, resizes them for the web and
// writes the credits module the site renders underneath each one.
//
//   node scripts/fetch-lesson-images.mjs path/to/image-manifest.json
//
// Every source is openly licensed (CC0, Public Domain, CC BY or CC BY-SA), and
// the credit line is generated here rather than typed by hand so an image can
// never end up on the site without its attribution.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const manifestPath = process.argv[2];
const OUT_DIR = "public/img/lessons";
const MODULE = "lib/lesson-images.ts";
const WIDTH = 800;

const UA =
  "cs.ub.mn-school-course-builder/1.0 (https://cs.ub.mn; school course material)";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
fs.mkdirSync(OUT_DIR, { recursive: true });

const done = [];
const failed = [];

for (const item of manifest) {
  try {
    let buf = null;
    for (let attempt = 0; attempt < 3 && !buf; attempt++) {
      const res = await fetch(item.src, { headers: { "User-Agent": UA } });
      if (res.ok) buf = Buffer.from(await res.arrayBuffer());
      else await sleep(1200);
    }
    if (!buf) throw new Error("could not fetch");

    const out = path.join(OUT_DIR, `${item.id}.webp`);
    const info = await sharp(buf)
      .resize({ width: WIDTH, withoutEnlargement: true })
      .webp({ quality: 72 })
      .toFile(out);

    done.push({
      ...item,
      file: `/img/lessons/${item.id}.webp`,
      width: info.width,
      height: info.height,
      bytes: info.size,
    });
    process.stdout.write(".");
    await sleep(250);
  } catch (e) {
    failed.push(`${item.id}: ${e.message}`);
    process.stdout.write("!");
  }
}

// Merge, do not replace. This used to rebuild the module from the manifest
// alone, so running it with a handful of new pictures silently deleted the
// credits — and therefore the images — for every lesson not mentioned. The
// existing entries are parsed back out and kept unless the manifest supersedes
// one. Attribution is a licence condition, not a nicety: losing it is the one
// failure here that actually matters.
if (fs.existsSync(MODULE)) {
  const prev = fs.readFileSync(MODULE, "utf8");
  const entries = [
    ...prev.matchAll(
      /"([^"]+)": \{\s*src: "([^"]*)",\s*width: (\d+),\s*height: (\d+),\s*title: "((?:[^"\\]|\\.)*)",\s*creator: "((?:[^"\\]|\\.)*)",\s*license: "((?:[^"\\]|\\.)*)",\s*source: "((?:[^"\\]|\\.)*)",/g,
    ),
  ];
  const fresh = new Set(done.map((d) => d.id));
  let kept = 0;
  for (const m of entries) {
    if (fresh.has(m[1])) continue;
    done.push({
      id: m[1], file: m[2], width: Number(m[3]), height: Number(m[4]),
      title: m[5], creator: m[6], license: m[7], source: m[8], bytes: 0,
    });
    kept++;
  }
  console.log(`\nkept ${kept} existing image(s) already in ${MODULE}`);
}

done.sort((a, b) => a.id.localeCompare(b.id));

const esc = (s) => (s ?? "").replace(/\\/g, "\\\\").replace(/"/g, '\\"').trim();

const body = done
  .map(
    (d) => `  "${d.id}": {
    src: "${d.file}",
    width: ${d.width},
    height: ${d.height},
    title: "${esc(d.title)}",
    creator: "${esc(d.creator) || "unknown"}",
    license: "${esc(d.license)}",
    source: "${esc(d.source)}",
  },`,
  )
  .join("\n");

fs.writeFileSync(
  MODULE,
  `// Generated by scripts/fetch-lesson-images.mjs — do not edit by hand.
//
// Photographs used in the lessons, with the credit each licence requires.
// Run the script again to refresh or add images.

export interface LessonImage {
  src: string;
  width: number;
  height: number;
  title: string;
  creator: string;
  license: string;
  /** Page the picture came from, linked in the credit line. */
  source: string;
}

export const LESSON_IMAGES: Record<string, LessonImage> = {
${body}
};

export function imageFor(id: string): LessonImage | null {
  return LESSON_IMAGES[id] ?? null;
}
`,
);

const total = done.reduce((s, d) => s + d.bytes, 0);
console.log(`\n\nsaved ${done.length} images, ${(total / 1048576).toFixed(2)} MB total`);
console.log(`  → ${OUT_DIR}/`);
console.log(`  → ${MODULE}`);
for (const f of failed) console.log("  ! " + f);
